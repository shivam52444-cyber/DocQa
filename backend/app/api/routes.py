from __future__ import annotations

import hmac
from dataclasses import dataclass
from uuid import UUID

from fastapi import APIRouter, BackgroundTasks, Depends, File, Header, Request, UploadFile

from app.container import Container
from app.errors import AppError, Unauthorized
from app.schemas import AskIn, AskOut, DocumentOut

router = APIRouter()


@dataclass(frozen=True)
class RequestContext:
    session_id: UUID  # lives while the user's browser tab lives
    query_id: UUID  # generated by the frontend on every backend call / click


def get_container(request: Request) -> Container:
    return request.app.state.container


async def get_ctx(
    c: Container = Depends(get_container),
    x_session_id: UUID = Header(...),
    x_query_id: UUID = Header(...),
    x_internal_token: str | None = Header(default=None),
) -> RequestContext:
    expected = c.settings.internal_api_token
    if expected is not None and not hmac.compare_digest((x_internal_token or "").encode(), expected.get_secret_value().encode()):
        raise Unauthorized("Unauthorized")
    await c.repo.ensure_session(x_session_id)
    return RequestContext(x_session_id, x_query_id)


# ------------------------------------------------------------------ health (no auth, no headers)
@router.get("/healthz", include_in_schema=False)
async def healthz() -> dict:
    return {"status": "ok"}


@router.get("/readyz", include_in_schema=False)
async def readyz(c: Container = Depends(get_container)) -> dict:
    try:
        await c.repo.ping()
    except Exception as exc:
        raise AppError("Database unavailable", code="not_ready", status_code=503) from exc
    return {"status": "ready"}


# ------------------------------------------------------------------ v1 API
@router.post("/v1/documents", response_model=DocumentOut, status_code=202)
async def upload_document(
    file: UploadFile = File(...), ctx: RequestContext = Depends(get_ctx), c: Container = Depends(get_container)
):
    """Stores the file and queues ingestion. Poll GET /v1/documents for status."""
    return await c.uploads.submit(ctx.session_id, ctx.query_id, file)


@router.get("/v1/documents", response_model=list[DocumentOut])
async def list_documents(ctx: RequestContext = Depends(get_ctx), c: Container = Depends(get_container)):
    return await c.repo.list_documents(ctx.session_id)


@router.post("/v1/ask", response_model=AskOut)
async def ask(
    body: AskIn,
    background: BackgroundTasks,
    ctx: RequestContext = Depends(get_ctx),
    c: Container = Depends(get_container),
):
    outcome = await c.rag.ask(ctx.session_id, ctx.query_id, body.question)
    if outcome.record is not None:
        background.add_task(c.repo.save_request_safe, outcome.record)  # audit log after the response is sent
    return outcome.response
